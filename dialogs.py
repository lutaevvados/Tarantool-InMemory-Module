"""
Вспомогательные утилиты для подсистемы диалогов.

Ключевая функция — make_dialog_id: детерминированно вычисляет UUID
диалога из пары пользователей. Независимо от порядка аргументов
(user_A ↔ user_B) всегда возвращает одинаковый dialog_id.

Именно по этому UUID шардируется таблица messages в Citus.

ВАЖНО — выбор ключа шардирования:
  Шардируем по dialog_id, а не по from_user_id.
  Это решает «Эффект Леди Гаги»: если бы мы шардировали по отправителю,
  все сообщения одной звезды (с миллионом диалогов) уходили бы на
  один shard. С dialog_id каждый диалог звезды попадает на свой shard —
  нагрузка распределяется равномерно.
"""

import uuid


def make_dialog_id(user_a: str, user_b: str) -> str:
    """
    Возвращает детерминированный UUID диалога между двумя пользователями.

    Алгоритм:
      1. Сортируем два UUID как строки (лексикографически).
      2. Конкатенируем: "<меньший>:<больший>".
      3. Вычисляем UUID5 (namespace + строка) — всегда одинаковый для пары.

    Пример:
      make_dialog_id("aaa...", "bbb...") == make_dialog_id("bbb...", "aaa...")
      → "3f4e2c1d-..."
    """
    pair = ":".join(sorted([user_a.lower(), user_b.lower()]))
    return str(uuid.uuid5(uuid.NAMESPACE_OID, pair))
